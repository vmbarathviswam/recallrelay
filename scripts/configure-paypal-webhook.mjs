import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {PayPal} from '../src/paypal.mjs';
const config=JSON.parse(await readFile('wrangler.local.jsonc','utf8'));
const origin=new URL(config.vars.APP_ORIGIN);
if(origin.protocol!=='https:'||!origin.hostname.endsWith('.workers.dev'))throw new Error('A deployed HTTPS Worker origin is required.');
const url=origin.origin+'/api/webhooks/paypal';
const paypal=new PayPal(process.env);
const events=['PAYMENT.CAPTURE.COMPLETED','PAYMENT.CAPTURE.REFUNDED','PAYMENT.REFUND.COMPLETED','PAYMENT.REFUND.PENDING','PAYMENT.REFUND.FAILED','PAYMENT.REFUND.DENIED','PAYMENT.REFUND.CANCELLED','CUSTOMER.DISPUTE.CREATED','CUSTOMER.DISPUTE.UPDATED','CUSTOMER.DISPUTE.RESOLVED'];
const existing=await paypal.call('/v1/notifications/webhooks');
let webhook=existing.webhooks?.find(x=>x.url===url);
if(!webhook)webhook=await paypal.call('/v1/notifications/webhooks',{method:'POST',body:{url,event_types:events.map(name=>({name}))}});
if(typeof webhook.id!=='string'||webhook.url!==url)throw new Error('Unexpected webhook registration response.');
const text=await readFile('.env','utf8');
const lines=text.split('\n');let found=false;
const updated=lines.map(line=>{if(line.startsWith('PAYPAL_WEBHOOK_ID=')){found=true;return 'PAYPAL_WEBHOOK_ID='+webhook.id;}return line;});
if(!found)updated.push('PAYPAL_WEBHOOK_ID='+webhook.id);
await writeFile('.env',updated.join('\n'));
await mkdir('outputs/sandbox-evidence',{recursive:true});
await writeFile('outputs/sandbox-evidence/webhook-registration.json',JSON.stringify({checkedAt:new Date().toISOString(),id:webhook.id,url:webhook.url,events:webhook.event_types?.map(x=>x.name)},null,2));
console.log(JSON.stringify({registered:true,url,eventTypes:webhook.event_types?.length,localConfigurationUpdated:true}));
